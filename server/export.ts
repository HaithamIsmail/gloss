/** The whole data folder: a snapshot of the database plus uploads and notebook folders. */
export function exportAll(): ZipStream {
  const tmp = path.join(os.tmpdir(), `gloss-export-${process.pid}-${Date.now()}.db`);
  writeSnapshot(tmp);
  const zip = new yazl.ZipFile();
  zip.addFile(tmp, "data/study.db");
  const walk = (dir: string, rel: string) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, e.name);
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (!rel && (e.name === "backups" || e.name.startsWith("study.db"))) continue;
      if (e.isDirectory()) walk(abs, r);
      else if (e.isFile()) zip.addFile(abs, `data/${r}`, { compress: !/\.(png|jpe?g|gif|webp|pdf|pptx?|zip|gz)$/i.test(e.name) });
    }
  };
  walk(DATA_DIR, "");
  zip.end();
  const d = new Date();
  const day = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
  return { name: `Gloss data ${day}.zip`, stream: zip.outputStream, cleanup: () => fs.rm(tmp, { force: true }, () => undefined) };
}
